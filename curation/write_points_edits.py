#!/usr/bin/env python3
"""Write curation/POINTS_EDITS.md, the record of every points edit with its source and process.  python curation/write_points_edits.py
The CSVs in this folder feed the dashboard and are to be archived once the work is complete; this file is the part to keep. It is generated, so rerun it after any change
(run calculated_points.py, explain_gaps.py and save_discrepancies.py first). Row-level edits for 1975-2003 come from points_<season>.csv and adjustments.json; the evidence for each
is looked up in known_notes.csv (the hand-written notes in save_discrepancies.py), otherwise it is the generic test that was used. Earlier seasons are derived and are summarised, not listed."""
import collections, csv, glob, json, os, re
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
norm = lambda s: re.sub(r"[^a-z]", "", s.lower())
rd = lambda p: list(csv.DictReader(open(os.path.join(HERE, p), encoding="utf-8")))

calc = {(int(r["season"]), int(r["race"]), int(r["finish"])): r for r in rd("calculated_points_1975_2003.csv")}
wiki_total = {}; wiki_page = {}
for p in sorted(glob.glob(os.path.join(HERE, "final_standings_*.csv"))):
    m = re.search(r"final_standings_(\d{4})\.csv$", p)
    if not m: continue
    s = int(m.group(1))
    for r in csv.DictReader(open(p, encoding="utf-8")):
        wiki_total[(s, norm(r["driver"]))] = float(r["pts"])
        t = re.match(r"Wikipedia: (.+?), section", r["source"])
        if t: wiki_page[s] = "https://en.wikipedia.org/wiki/" + t.group(1).replace(" ", "_")
notes = {(int(r["season"]), norm(r["driver"])): r["note"] for r in rd("known_notes.csv")}
adj = collections.defaultdict(list)
for a in json.load(open(os.path.join(ROOT, "adjustments.json"), encoding="utf-8")):
    adj[a["season"]].append(a)
by_driver = collections.defaultdict(list)
for r in calc.values(): by_driver[(int(r["season"]), norm(r["driver"]))].append(r)

ordinal = lambda n: f"{n}{'th' if 10 <= n % 100 <= 20 else {1: 'st', 2: 'nd', 3: 'rd'}.get(n % 10, 'th')}"
edits = []; per = collections.defaultdict(list)
for p in sorted(glob.glob(os.path.join(HERE, "points_19[789]*.csv")) + glob.glob(os.path.join(HERE, "points_200*.csv"))):
    s = int(re.search(r"points_(\d{4})\.csv$", p).group(1))
    if s < 1975: continue
    for e in rd(os.path.basename(p)):
        c = calc[(s, int(e["race"]), int(e["finish"]))]; per[(s, norm(c["driver"]))].append((e, c))
for k, rows in per.items():
    s = k[0]; after = sum(float(x["final_pts"]) for x in by_driver[k])
    before = after - sum(float(c["final_pts"]) - (float(c["source_pts"]) if c["source_pts"] else 0) for e, c in rows)
    for e, c in rows:
        edits.append((s, int(e["race"]), c["race_name"], c["driver"], int(c["finish"]), c["source_pts"] or "blank", e["pts"], wiki_total.get(k), before, after, k))
edits.sort()
def why(k):
    if k in notes: return notes[k]
    rows = per[k]; scores = [float(c["calc_pts"]) for e, c in rows]
    one = len(scores) == 1; total = f"{scores[0]:g}" if one else f"{' + '.join(f'{x:g}' for x in scores)} = {sum(scores):g}"
    return (f"The formula score for the restored {'row' if one else 'rows'} ({total}) equals the gap between Wikipedia's total "
            f"({wiki_total.get(k, float('nan')):g}) and the data total before the edit ({edits_before[k]:g}); no other test was applied. Convention: a zero is restored only when the driver is in Wikipedia's table and Wikipedia's total confirms the missing points")
edits_before = {e[10]: e[8] for e in edits}

fits = collections.Counter(); noted = collections.Counter()
for r in rd("gap_explanations_1975_2003.csv"): fits[r["fits"]] += 1; noted[r["noted"]] += 1
src_err = [r for r in rd("discrepancies.csv") if r["kind"] == "source_error"]
older = {}
for p in sorted(glob.glob(os.path.join(HERE, "points_19[4-7]*.csv"))):
    s = int(re.search(r"points_(\d{4})\.csv$", p).group(1))
    if s < 1975: older[s] = (len(rd(os.path.basename(p))), len(adj.get(s, [])))

L = []; w = L.append
w("# Points edits: sources and process\n")
w("The CSVs in `curation/` feed the dashboard and are to be archived once the work is complete. **This file is the part to keep.** It is generated by `curation/write_points_edits.py`; "
  "do not edit it by hand, change the data or notes and rerun.\n")
w("## Process\n")
w("1. **Race points are computed, not trusted from a site's total.** For 1975-2003 the points for a result are the scoring formula applied to the finishing position and laps led: "
  "175, 170, 165, 160, 155, 150, 146, 142, 138, 134, 130, 127 for 1st to 12th, then 3 fewer per place; +5 for leading a lap and +5 more for the most laps led in the race. "
  "Only 7 non-zero rows in 1975-2003 break the formula (`calculated_points_1975_2003.csv`, column `diff`). Finishing positions are the authority.")
w("2. **Wikipedia's final-standings table is the comparison, not the authority.** `fetch_wikipedia_standings.py` stores each season's table in `final_standings_<season>.csv` (the page title is in its `source` column). "
  "Where a driver's data total differs from Wikipedia's, the gap is a question about the source, not a reason to change a race row.")
w("3. **A row is changed only when evidence supports it.** The evidence is one of: a single zero-point row whose formula score equals the gap exactly, confirmed by Wikipedia's total (a missing row is restored); "
  "a results page showing the points (Jayski, Driver Averages and Racing-Reference pages supplied by the project owner); or a quoted article (penalties). Restored rows go in `points_<season>.csv` with `override=1`.")
w("4. **The Pts column shows standings values.** A zero can mean \"does not count\" (a driver not in the standings, or an entry the standings leave out). Such zeros stay. A zero is restored only for a driver in Wikipedia's table whose total confirms the missing points.")
w("5. **Penalties and unexplained differences are standings adjustments**, in `adjustments.json`, applied from a stated race. They never alter a race row.")
w("6. **Nothing is scraped.** Racing-Reference is behind a bot check and Driver Averages' robots.txt disallows scrapers, so every page below is the project owner's report (a screenshot or quoted text, pages not fetched by the tooling) and is recorded as such.\n")
w("To rerun: `python curation/calculated_points.py`, `python curation/explain_gaps.py`, `python curation/save_discrepancies.py`, `python curation/write_points_edits.py`.\n")

w("## Sources\n")
w("- **Wikipedia season articles** (final standings, CC BY-SA 4.0), by season:")
for s in sorted(wiki_page): w(f"  - {s}: <{wiki_page[s]}>")
w("- **Racing-Reference** year pages (1949-1974, used for the race fields and purses): `http://racing-reference.info/yeardet/<year>/W`. Driver season pages are used one at a time: "
  "<https://www.racing-reference.info/driver-season-stats/bouchke01/1993/W> (Ken Bouchard 1993).")
w("- **Jayski:** 2002 penalties table <https://www.jayski.com/nascar-cup-series/2002-nascar-penalties/>; Gordon 2000 penalty <https://www.jayski.com/2000/09/13/gordons-engine-problem-update-6-the-penalty-the-appeal-the-reactions/>; "
  "1984 Miller High Life 400 (Richmond) <https://www.jayski.com/race-results/1984-nascar-winston-cup-series/miller-high-life-400-richmond/>. Jayski has no driver points.")
w("- **Driver Averages** (the same source as nascaR.data, so agreement with it is one source twice): results and standings pages supplied as screenshots; no stable links recorded.")
w("- **nascaR.data** `cup_series.parquet` (GPL-3, from DriverAverages.com).\n")

w("## Race-row edits, 1975-2003\n")
w(f"{len(edits)} rows. `Source` is Pts as in nascaR.data, `New` is the value in `points_<season>.csv`; the totals are for the driver's whole season.\n")
w("| Season | Race | Driver | Finish | Source | New | Wikipedia total | Data total before | after |")
w("|---|---|---|---|---|---|---|---|---|")
for e in edits:
    w(f"| {e[0]} | {e[1]} {e[2]} | {e[3]} | {e[4]} | {e[5]} | {e[6]} | {'' if e[7] is None else format(e[7], 'g')} | {e[8]:g} | {e[9]:g} |")
w("")
w("### Evidence per driver\n")
done = set()
for e in edits:
    k = (e[0], norm(e[3]))
    if k in done: continue
    done.add(k)
    races = ", ".join(f"race {x[1]} ({ordinal(x[4])}, {x[6]})" for x in edits if (x[0], norm(x[3])) == k)
    w(f"- **{e[3]} {e[0]}**: {races}. {why(k)}")
w("")

w("## Standings adjustments, 1975-2003 (`adjustments.json`)\n")
w("| Season | From race | Driver | Points | Note |")
w("|---|---|---|---|---|")
for s in sorted(adj):
    if s < 1975 or s > 2003: continue
    for a in adj[s]: w(f"| {s} | {a['race']} | {a['driver']} | {a['pts']:+g} | {a['note']} |")
w("")

w("## Seasons before 1975 (derived)\n")
w("Race points for 1949-51, 1955, 1972 and 1973 were derived from purses, race class and the scoring scale, then reconciled to Wikipedia's totals with adjustments. They are not row-by-row source values, "
  "and the derivation scripts hold the method: `reconcile_1949.py`, `derive_points_prize.py` (1950-51), `derive_points_1955.py`, `derive_points_1972_73.py`. Provenance and per-season findings are in `SOURCES.md` and `WIKIPEDIA_SUMMARY.md`.\n")
w("| Season | Rows in points file | Reconcile adjustments |")
w("|---|---|---|")
for s, (n, a) in sorted(older.items()): w(f"| {s} | {n} | {a} |")
w("")

w("## Errors found in Wikipedia's tables\n")
for r in src_err: w(f"- **{r['season']} {r['subject']}**: {r['detail']}")
w("- Also Wikipedia errors, corrected on Wikipedia by the project owner and confirmed by a re-fetch: Ron Fellows 1999, and in 1993 Mike Skinner (55 for 58, a typo), Ken Schrader (3,714 for 3,715) and Butch Gilliland (63 for 67). The 1981 group below is not corrected.\n")

w("## Open differences, 1975-2003\n")
w(f"{sum(fits.values())} drivers still differ from Wikipedia's total after the edits above; {noted['1']} are noted as explained or probable errors, {noted['0']} are not yet noted. By what fits (see `explain_gaps.py`): "
  + ", ".join(f"{k} {v}" for k, v in fits.most_common()) + ".\n")
w("The 1981 group (22 drivers exactly 3 under Wikipedia's total) is consistent with one race, the Atlanta Journal 500 (race 30), being scored one place down for 13th and lower on Wikipedia's side; "
  "this is an inference from the pattern, not a shown cause.\n")
open(os.path.join(HERE, "POINTS_EDITS.md"), "w", encoding="utf-8").write("\n".join(L))
print("wrote POINTS_EDITS.md:", len(edits), "row edits;", sum(len(v) for k, v in adj.items() if 1975 <= k <= 2003), "adjustments")
